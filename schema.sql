-- ---------- Trigger: movimenti e data dismissione automatici ----------
-- Sostituisce lo script onEdit (registraMovimento).
CREATE FUNCTION asset_registra_movimento() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_fuori_nuovo boolean;
  v_fuori_vecchio boolean;
  v_tipo text;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    SELECT fuori INTO v_fuori_nuovo   FROM stato_asset WHERE nome = NEW.stato;
    SELECT fuori INTO v_fuori_vecchio FROM stato_asset WHERE nome = OLD.stato;
    -- data dismissione: si compila entrando in uno stato di uscita, si svuota se rientra
    IF v_fuori_nuovo AND NOT v_fuori_vecchio AND NEW.data_dismissione IS NULL THEN
      NEW.data_dismissione := current_date;
    ELSIF NOT v_fuori_nuovo AND v_fuori_vecchio THEN
      NEW.data_dismissione := NULL;
    END IF;

    IF NEW.persona_id IS DISTINCT FROM OLD.persona_id THEN
      v_tipo := CASE WHEN OLD.persona_id IS NULL THEN 'Consegna'
                     WHEN NEW.persona_id IS NULL THEN 'Riconsegna'
                     ELSE 'Riassegnazione' END;
      INSERT INTO movimento (asset_id, tipo, da_persona_id, a_persona_id, stato_prima, stato_dopo)
      VALUES (NEW.id, v_tipo, OLD.persona_id, NEW.persona_id, OLD.stato, NEW.stato);
    END IF;

    IF NEW.stato IS DISTINCT FROM OLD.stato THEN
      SELECT movimento INTO v_tipo FROM stato_asset WHERE nome = NEW.stato;
      INSERT INTO movimento (asset_id, tipo, da_persona_id, a_persona_id, stato_prima, stato_dopo)
      VALUES (NEW.id, v_tipo, OLD.persona_id, NEW.persona_id, OLD.stato, NEW.stato);
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER asset_movimenti BEFORE UPDATE ON asset
  FOR EACH ROW EXECUTE FUNCTION asset_registra_movimento();

-- ---------- Viste ----------
-- Equivalente delle viste ▸ e del conteggio "asset vivi"
CREATE VIEW v_asset AS
SELECT a.id, a.codice, a.tipologia, a.stato, p.nome || ' ' || p.cognome AS assegnato_a,
       a.marca, a.modello, a.ram_gb, a.storage_gb, a.sistema_operativo, a.serial, a.hostname,
       az.nome AS azienda, c.numero AS cespite, f.nome AS fornitore, fa.numero AS n_fattura,
       a.data_acquisto, extract(year FROM a.data_acquisto)::int AS anno,
       a.importo, a.data_dismissione, a.note, s.fuori
FROM asset a
JOIN stato_asset s ON s.nome = a.stato
JOIN azienda az    ON az.id = a.azienda_id
LEFT JOIN persona p      ON p.id = a.persona_id
LEFT JOIN cespite c      ON c.id = a.cespite_id
LEFT JOIN fattura fa     ON fa.id = a.fattura_id
LEFT JOIN fornitore f    ON f.id = a.fornitore_id;

CREATE VIEW v_asset_vivi AS SELECT * FROM v_asset WHERE NOT fuori;

-- Riepilogo: una riga per azienda e tipologia, una colonna per stato, importo sui 4 stati
CREATE VIEW v_riepilogo AS
SELECT az.nome AS azienda, t.nome AS tipologia,
  count(*) FILTER (WHERE a.stato = 'Assegnato')       AS assegnato,
  count(*) FILTER (WHERE a.stato = 'In esercizio')    AS in_esercizio,
  count(*) FILTER (WHERE a.stato = 'Disponibile')     AS disponibile,
  count(*) FILTER (WHERE a.stato = 'Da verificare')   AS da_verificare,
  count(*) FILTER (WHERE a.stato = 'Non aziendale')   AS non_aziendale,
  count(*) FILTER (WHERE a.stato = 'Estinto')         AS estinto,
  count(*) FILTER (WHERE a.stato = 'Venduto')         AS venduto,
  count(*) FILTER (WHERE a.stato = 'Ceduto')          AS ceduto,
  count(*) FILTER (WHERE a.stato = 'Macerato')        AS macerato,
  count(*) FILTER (WHERE a.stato = 'Smarrito/Rubato') AS smarrito_rubato,
  count(a.id)                                         AS totale,
  coalesce(sum(a.importo) FILTER (WHERE s.in_importo), 0) AS importo
FROM azienda az
CROSS JOIN tipologia t
LEFT JOIN asset a ON a.azienda_id = az.id AND a.tipologia = t.nome
LEFT JOIN stato_asset s ON s.nome = a.stato
GROUP BY az.nome, t.nome;

CREATE VIEW v_acquisti_per_anno AS
SELECT az.nome AS azienda, extract(year FROM a.data_acquisto)::int AS anno,
       count(*) AS n_asset, sum(a.importo) AS valore
FROM asset a JOIN azienda az ON az.id = a.azienda_id
WHERE a.data_acquisto IS NOT NULL
GROUP BY 1, 2;

-- Antivirus: confronto fra PC Windows attivi e ultimo report importato.
-- Nomi Windows troncati a 15 caratteri (NetBIOS): corrispondenza esatta o sul prefisso di 15.
CREATE FUNCTION host_norm(t text) RETURNS text LANGUAGE sql IMMUTABLE AS
$$ SELECT regexp_replace(upper(coalesce(t,'')), '[^A-Z0-9-]', '', 'g') $$;

CREATE VIEW v_controllo_antivirus AS
WITH ultimo AS (SELECT id, importato FROM antivirus_import ORDER BY id DESC LIMIT 1),
rep AS (SELECT d.*, host_norm(d.dispositivo) AS h, u.importato
        FROM antivirus_dispositivo d JOIN ultimo u ON u.id = d.import_id)
SELECT a.codice, a.azienda, a.stato, a.assegnato_a, a.hostname,
       CASE WHEN r.dispositivo IS NULL THEN 'Mancante'
            WHEN r.stato = 'Protetto' AND r.ultimo_rilevato >= r.importato - interval '20 days' THEN 'OK'
            ELSE 'Da verificare' END AS antivirus,
       r.dispositivo AS dispositivo_report, r.ultimo_rilevato
FROM v_asset_vivi a
LEFT JOIN rep r
  ON host_norm(a.hostname) <> ''
 AND (r.h = host_norm(a.hostname) OR left(r.h,15) = left(host_norm(a.hostname),15))
-- Regola: ogni PC/Server Windows ATTIVO (Assegnato, In esercizio, Da verificare) deve avere un antivirus.
-- Sistema operativo vuoto = si presume Windows. Estinto/Disponibile non sono "attivi".
WHERE a.tipologia IN ('PC','Server')
  AND (a.sistema_operativo IS NULL OR a.sistema_operativo ILIKE 'Windows%')
  AND a.stato IN ('Assegnato','In esercizio','Da verificare');

COMMIT;
