-- Schema PostgreSQL (bozza 1). Sostituisce il foglio Inventario_IT_2026.
-- Tabelle di anagrafica -> asset -> movimenti; Riepilogo, Dashboard, viste ▸
-- e Controllo Antivirus sono VIEW in fondo al file.

BEGIN;

-- ---------- Anagrafiche ----------
CREATE TABLE azienda (
  id    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome  text NOT NULL UNIQUE
);

CREATE TABLE fornitore (
  id    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome  text NOT NULL UNIQUE          -- una sola grafia: "Effesistemi", non "EFFESISTEMI srl a socio unico"
);

CREATE TABLE tipologia (
  nome  text PRIMARY KEY              -- PC, Mac, Tablet, Telefono, Server, Monitor, Stampante, Rete, Altro
);

-- Gli stati portano con sé le regole che prima stavano nello script
CREATE TABLE stato_asset (
  nome        text PRIMARY KEY,
  fuori       boolean NOT NULL,       -- true = "non ce l'abbiamo più": sparisce da viste e conteggi
  in_importo  boolean NOT NULL,       -- true = entra nell'importo del Riepilogo (Assegnato+In esercizio+Disponibile+Estinto)
  movimento   text NOT NULL,          -- nome del movimento registrato quando si entra in questo stato
  ordine      smallint NOT NULL
);

CREATE TABLE persona (
  id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome           text NOT NULL,
  cognome        text NOT NULL,
  email          text UNIQUE,
  azienda_id     smallint REFERENCES azienda,
  reparto        text,
  stato          text NOT NULL DEFAULT 'Attivo' CHECK (stato IN ('Attivo','Sospeso','Cessato')),
  stato_workspace text,               -- arriva dalla sincronizzazione Google Workspace
  data_ingresso  date,
  data_uscita    date,
  note           text,
  UNIQUE (nome, cognome)
);

-- Un cespite contabile (numero o codice alfanumerico) può coprire più asset (es. cespite 80 = 3 PC identici)
CREATE TABLE cespite (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  azienda_id  smallint NOT NULL REFERENCES azienda,
  numero      text NOT NULL CHECK (numero ~ '^[A-Z0-9][A-Z0-9._/-]{0,29}$'),   -- alfanumerico, maiuscolo (es. 48, A12, 2019/07)
  note        text,
  UNIQUE (azienda_id, numero)
);

CREATE TABLE fattura (
  id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fornitore_id  int NOT NULL REFERENCES fornitore,
  numero        text NOT NULL,        -- senza spazi iniziali/finali
  data          date,
  UNIQUE (fornitore_id, numero, data), -- "255" esiste sia per Effesistemi 2023 sia per Wind 2023
  UNIQUE (id, fornitore_id)
);

-- Cespiti ante 2018: copia di sola lettura del foglio storico, per la quadratura con l'amministrazione.
-- Non collegata ad azienda/asset: il foglio non indica l'azienda e i numeri si sovrappongono (Cart'armata e Le parole).
CREATE TABLE cespite_storico (
  id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria     text NOT NULL,            -- computer, mac, tablet, eliminati
  numero        int NOT NULL UNIQUE,
  data          date,
  fornitore     text,                     -- come scritto nel foglio, senza normalizzazione
  descrizione   text,
  col_h         numeric(10,2),            -- colonna "Col H" del foglio (significato non documentato)
  da_trovare_eliminare numeric(10,2),
  da_abbinare   numeric(10,2),
  note          text
);

-- ---------- Asset ----------
CREATE TABLE asset (
  id               int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codice           text GENERATED ALWAYS AS ('AST-' || lpad(id::text, 3, '0')) STORED UNIQUE,
  tipologia        text NOT NULL REFERENCES tipologia,
  stato            text NOT NULL REFERENCES stato_asset,
  persona_id       int REFERENCES persona,         -- "Assegnato a"
  marca            text,
  modello          text,
  ram_gb           smallint CHECK (ram_gb BETWEEN 1 AND 1024),
  storage_gb       int CHECK (storage_gb > 0),
  sistema_operativo text,
  serial           text,
  hostname         text,                            -- "Nome dispositivo"
  azienda_id       smallint NOT NULL REFERENCES azienda,
  cespite_id       int REFERENCES cespite,
  fornitore_id     int REFERENCES fornitore,        -- anche senza fattura (es. AST-081)
  fattura_id       int,
  data_acquisto    date,
  importo          numeric(10,2) CHECK (importo >= 0),
  data_dismissione date,
  note             text,
  FOREIGN KEY (fattura_id, fornitore_id) REFERENCES fattura (id, fornitore_id), -- fornitore dell'asset = fornitore della fattura
  -- Regola: assegnatario se e solo se Assegnato (o Da verificare/Non aziendale, dove può esserci).
  CONSTRAINT assegnatario_coerente CHECK (
    (stato = 'Assegnato' AND persona_id IS NOT NULL)
    OR (stato IN ('In esercizio','Disponibile','Estinto','Venduto','Ceduto','Macerato','Smarrito/Rubato') AND persona_id IS NULL)
    OR stato IN ('Da verificare','Non aziendale')
  )
);
CREATE UNIQUE INDEX asset_serial_uq ON asset (upper(serial)) WHERE serial IS NOT NULL AND serial <> '';
CREATE INDEX asset_persona_ix  ON asset (persona_id);
CREATE INDEX asset_stato_ix    ON asset (stato);
CREATE INDEX asset_hostname_ix ON asset (upper(hostname));

CREATE TABLE sim (
  id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codice       text GENERATED ALWAYS AS ('SIM-' || lpad(id::text, 3, '0')) STORED UNIQUE,
  numero       text UNIQUE,
  stato        text NOT NULL CHECK (stato IN ('Attiva','Sospesa','Cessata','Da verificare')),
  persona_id   int REFERENCES persona,
  operatore    text,
  piano        text,
  costo_mensile numeric(8,2),
  azienda_id   smallint REFERENCES azienda,
  asset_id     int REFERENCES asset,               -- telefono in cui è montata (prima: testo libero)
  giga_telefono text,
  saponetta    boolean,
  giga_saponetta text,
  note         text
);

-- ---------- Storico ----------
CREATE TABLE movimento (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data          date NOT NULL DEFAULT current_date,
  tipo          text NOT NULL,                     -- Consegna, Riconsegna, Riassegnazione, <movimento dello stato>, Cambio stato
  asset_id      int REFERENCES asset ON DELETE SET NULL, -- NULL = asset eliminato (vedi oggetto) o eliminazione di persona/SIM
  da_persona_id int REFERENCES persona,
  a_persona_id  int REFERENCES persona,
  stato_prima   text,
  stato_dopo    text,
  note          text,
  automatico    boolean NOT NULL DEFAULT true,
  oggetto       text,                              -- descrizione di ciò che è stato eliminato / dell'asset eliminato
  utente        text                               -- chi ha fatto l'operazione (email)
);
CREATE INDEX movimento_asset_ix ON movimento (asset_id, data);

-- ---------- Antivirus ----------
CREATE TABLE antivirus_import (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  importato  timestamptz NOT NULL DEFAULT now(),
  file_nome  text
);
CREATE TABLE antivirus_dispositivo (
  import_id      int NOT NULL REFERENCES antivirus_import ON DELETE CASCADE,
  dispositivo    text NOT NULL,
  stato          text,                              -- Protetto, ...
  utente         text,
  sistema_operativo text,
  ultimo_rilevato timestamptz,
  ip_locale      text,
  mac            text,
  PRIMARY KEY (import_id, dispositivo)
);

